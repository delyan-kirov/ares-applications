// Headless smoke test for the browser build: load `site/playground.wasm` in
// Node through the very same host bridge and language-server client the page
// uses (web/src/), run programs, drive the server, and assert the results.
// Exits non-zero on any failure.
//
// This tests whatever `site/playground.wasm` currently holds. `node web/build.ts`
// rebuilds it and then runs this, which is the order you want.

import { readFile } from "node:fs/promises";
import { createHost, Mode } from "./src/host.ts";
import { Client, type Diagnostic } from "./src/lsp.ts";
import { readCells } from "./cells.ts";

const host = createHost();
const bytes = await readFile(new URL("./site/playground.wasm", import.meta.url));
const { instance } = await WebAssembly.instantiate(bytes, host.imports);
host.bind(instance.exports);

const isErr = (text: string) => /error|mismatch|unbound|cannot|fault|unavailable/i.test(text.split("\n")[0]);

let failures = 0;
function check(name: string, ok: boolean, detail: string): void {
  if (ok) {
    console.log(`ok   ${name}`);
  } else {
    console.error(`FAIL ${name}\n${detail}`);
    failures++;
  }
}

// [name, mode, source, expected substrings]
const CASES: [string, Mode, string, string[]][] = [
  ["hello", Mode.Run,
    `$ @mod MAIN\n\n$ with HOST\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args =\n\tHOST.print "hi"; 0\n`,
    ["hi"]],
  ["fib", Mode.Run,
    `$ @mod MAIN\n\n$ with STR\n$ with HOST\n\n$ fib : @Int -> @Int = \\n =\n\tif n < 2 => n\n\telse fib (n - 1) + fib (n - 2)\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args =\n\tHOST.print (STR.from_int (fib 20)); 0\n`,
    ["6765"]],
  ["target reflection", Mode.Run,
    `$ @mod MAIN\n\n$ with HOST\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args =\n\tHOST.print TARGET.name; 0\n`,
    ["wasm32"]],
  ["emit C", Mode.C,
    `$ @mod MAIN\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args = 0\n`,
    ["Generated by the Thrax ccg backend"]],
  ["newer stdlib (LIST)", Mode.Run,
    `$ @mod MAIN\n\n$ with LIST\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args = 0\n`,
    ["exit 0"]],
];

for (const [name, mode, src, wants] of CASES) {
  const text = host.compile(src, mode);
  const missing = wants.filter((w) => !text.includes(w));
  check(name, !isErr(text) && missing.length === 0, `missing ${JSON.stringify(missing)}\n${text}`);
}

// Every tour cell the page ships must compile and run cleanly, so a broken
// example can never reach the site.
const cells = readCells();
for (const cell of cells) {
  const text = host.compile(cell.src, Mode.Run);
  check(`cell:${cell.id}`, !isErr(text) && text.length > 0, text);
}

host.register("shout", (s) => String(s).toUpperCase());
const shout = host.compile(
  `$ @mod MAIN\n\n$ echo : @Str -> @Str = @extern "WASM" "shout" ""\n\n` +
    `$ with HOST\n\n$ @main : @Vec @Str -> <@IO> @Int = \\args = HOST.print (echo "hi there"); 0\n`,
  Mode.Run,
);
check("register (host function added without a rebuild)", shout.includes("HI THERE"), shout);

// -- the language server ------------------------------------------------------

const client = new Client(host);
const published = new Map<string, Diagnostic[]>();
client.onDiagnostics = (uri, _version, diagnostics) => published.set(uri, diagnostics);
const errors = (uri: string) => (published.get(uri) ?? []).filter((d) => d.severity === 1);

check("lsp: semantic token legend", client.tokenTypes.includes("keyword"), JSON.stringify(client.tokenTypes));
check("lsp: highlight", client.highlight(cells[0].src).length > 0, "no tokens");

// The server and the compiler must agree: no tour cell has an error.
for (const cell of cells) {
  const uri = `file:///playground/${cell.id}.thx`;
  const started = performance.now();
  client.open(uri, cell.src);
  client.hover(uri, { line: 0, character: 0 });
  const took = (performance.now() - started).toFixed(0);
  check(`lsp: cell:${cell.id} checks clean (${took} ms)`, published.has(uri) && errors(uri).length === 0,
    JSON.stringify(published.get(uri) ?? "nothing published", null, 1));
  client.close(uri);
}

const uri = "file:///playground/broken.thx";
const broken = `$ @mod MAIN\n\n$ with STR\n$ with HOST\n\n$ n : @Int = 41\n\n` +
  `$ @main : @Vec @Str -> <@IO> @Int = \\args =\n    HOST.print (STR.from_int n);\n    n + "1"\n`;
client.open(uri, broken);
const type = client.hover(uri, { line: 5, character: 2 });
check("lsp: hover shows a type", type?.includes("n : @Int") ?? false, String(type));
check("lsp: a type error is reported", errors(uri).length > 0, JSON.stringify(published.get(uri)));
check("lsp: one error is the focus", errors(uri).some((d) => d.data?.role === "focus"),
  JSON.stringify(published.get(uri)));

const started = performance.now();
client.change(uri, broken.replace(`n + "1"`, "n + 1"));
client.hover(uri, { line: 5, character: 2 });
const took = (performance.now() - started).toFixed(0);
check(`lsp: an edit re-checks incrementally (${took} ms)`, errors(uri).length === 0, JSON.stringify(published.get(uri)));

const fixed = broken.replace(`n + "1"`, "n + 1");
const line = fixed.split("\n").findIndex((l) => l.includes("STR.from_int"));
const at = { line, character: fixed.split("\n")[line].indexOf("STR.") + 4 };
const items = client.completion(uri, at).map((i) => i.label);
check("lsp: completes a module's members", items.includes("from_int"), JSON.stringify(items.slice(0, 20)));

client.change(uri, "$ @mod MAIN\n$ x : @Int =   1\n");
const edits = client.formatting(uri);
check("lsp: formats", edits.length > 0, JSON.stringify(edits));

client.close(uri);
client.dispose();

if (failures) {
  console.error(`web/smoke: ${failures} case(s) failed`);
  process.exit(1);
}
console.log("web/smoke: OK, the browser build runs and its language server answers");
